    def process(self, context) -> float:
        """
        Run the complete pipeline for one frame.
        Returns pipeline latency in ms.
        Never raises — all exceptions are caught and logged per processor.
        """
        with self._pipeline_lock:
            pipeline_start = time.perf_counter()

            # Reset transient statuses
            for entry in self._processors.values():
                if entry.status == "SKIPPED":
                    entry.status = "READY" if entry.processor else "NOT_INITIALIZED"
                elif entry.status == "FAILED" and entry.processor is not None:
                    entry.status = "READY"
                    entry.error = None

            # Determine camera identity
            cam_id = str(getattr(getattr(context, "current_frame", None), "camera_id", "camera_1") or "camera_1")
            is_camera_2 = (cam_id == "camera_2")

            # Camera 1 runs all 19 stages.
            # Camera 2 runs object/person detection, AudioDeviceDetector, and approved rule evaluation/persistence.
            # It strictly bypasses FaceMesh, solvePnP head pose, EAR/MAR, GazeExtractor, BlinkDetector,
            # FaceIdentity, and IdentityProtection.
            stages_to_run = self._pipeline_order
            if is_camera_2:
                stages_to_run = [
                    "ObjectDetector",
                    "ObjectFilter",
                    "ObjectTracker",
                    "ObjectValidator",
                    "AudioDeviceDetector",
                    "ObservationFusion",
                    "RuleEngine",
                    "RiskEngine",
                    "ViolationManager",
                ]

            for name in stages_to_run:
                # Camera 1 microphone voice state ingestion before ObservationFusion
                if name == "ObservationFusion" and not is_camera_2:
                    try:
                        from ai_engine.audio_detection.voice_vad_worker import voice_vad_worker
                        is_speaking, db, noise, prob = voice_vad_worker.get_audio_state()
                        if hasattr(context, "audio_info"):
                            a_info = context.audio_info
                            if a_info is not None:
                                a_info.is_speaking = is_speaking
                                a_info.db_level = db
                                a_info.noise_level = noise
                                context.audio_info = a_info
                    except Exception as e:
                        logger.debug(f"Error reading audio info from VoiceVADWorker: {e}")

                self._run_step(name, context)
                # Face, iris, pose and object quality are now available. Update the
                # personalised screen-gaze baseline before fusion/rules consume it (Camera 1 only).
                if name == "IdentityProtection" and not is_camera_2:
                    try:
                        self._update_calibrated_attention(context)
                    except Exception as e:
                        logger.warning(f"Error updating calibrated attention: {e}")

            # Structured Per-Frame Debug Trace Logging (Issue 8)
            frame_id = getattr(getattr(context, "current_frame", None), "frame_id", self._total_frames_processed)
            oi = getattr(context, "object_info", None)
            curr_dets = getattr(oi, "current_detections", []) or []
            filt_dets = getattr(oi, "filtered_detections", []) or []
            trac_objs = getattr(oi, "tracked_objects", []) or []
            vali_objs = getattr(oi, "validated_objects", []) or []
            rules_res = getattr(context, "rule_results", None)
            trig_rules = [e.rule_id for e in getattr(rules_res, "evaluations", []) if getattr(e, "triggered", False)] if rules_res else []
            beha_res = getattr(context, "behavior_result", None)
            active_beh = beha_res.get("summary", {}).get("composite_behaviors_detected", []) if isinstance(beha_res, dict) else []

            if curr_dets or filt_dets or trac_objs or vali_objs or trig_rules or active_beh:
                def _fmt_dets(det_list):
                    return ", ".join([f"{getattr(getattr(x, 'object_type', None), 'name', str(getattr(x, 'object_type', None)))} ({getattr(x, 'confidence', 0.0):.2f})" for x in det_list]) or "None"
                def _fmt_tracks(trk_list):
                    return ", ".join([f"{getattr(getattr(x, 'object_type', None), 'name', str(getattr(x, 'object_type', None)))} Track #{getattr(x, 'tracking_id', '?')}" for x in trk_list]) or "None"

                logger.debug(
                    f"[FRAME {frame_id} PIPELINE TRACE]\n"
                    f"  YOLO: {_fmt_dets(curr_dets)}\n"
                    f"  Filter: {_fmt_dets(filt_dets)}\n"
                    f"  Tracker: {_fmt_tracks(trac_objs)}\n"
                    f"  Validator: {_fmt_dets(vali_objs)}\n"
                    f"  RuleEngine: {', '.join(trig_rules) or 'None'}\n"
                    f"  Behavior: {', '.join(active_beh) or 'None'}"
                )

            # Ensure context always carries evidence_store for persistence adapter
            context.evidence_store = getattr(self, "evidence_store", [])
            # Notify downstream Incident Integration Manager (Packages 10.1 - 10.9)
            if getattr(self, "integration_manager", None):
                try:
                    self.integration_manager.handle_frame_lifecycle_events(context)
                except Exception as e:
                    logger.error(f"Downstream Incident Integration Manager exception: {e}")

            pipeline_ms = (time.perf_counter() - pipeline_start) * 1000
            self._total_frames_processed += 1
            self._total_pipeline_ms += pipeline_ms

            return pipeline_ms

